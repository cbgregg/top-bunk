#!/usr/bin/env node
// Renders the TOP BUNK trailer from the game, frame by frame, in headless Chromium with a frozen clock, then cuts the
// soundtrack with ffmpeg: the song (the original placeholder, or a licensed recording via --music) laid under the picture and warped as the
// shots go wrong, the game's own sound effects and voice lines at their cue times, the hard cut to silence, the scare.
//
//   node trailer/render.js --preset preview            640x360 @ 12 fps, the landscape cut (2:19)
//   node trailer/render.js --preset steam              1920x1080 @ 30 fps, the Steam upload (use --gpu --headed for this one)
//   node trailer/render.js --preset social-preview     360x640 @ 12 fps, the portrait cut (22 s)
//   node trailer/render.js --preset social             1080x1920 @ 30 fps
//   --music FILE        a licensed recording (any format ffmpeg reads); default trailer/music/placeholder.wav (generated by gen_music.js if missing)
//   --out DIR           where the mp4s go (default trailer/out)        --scratch DIR   where the PNG frames go (default $TMPDIR/topbunk-trailer)
//   --quality Q         ultra|high|medium|low (default: high for steam/social, medium for previews)   --shadow N   shadow map size (sun; spots get N/2)
//   --res F             render scale 0.5..1 (SwiftShader speed knob; the picture is upscaled)   --fps N   override the preset's frame rate
//   --contact           capture only the middle frame of every shot (a fast check of the shot list; no video is encoded)
//   --every N           capture every Nth frame   --range A-B   capture frames A..B only   --resume   skip frames whose PNG already exists
//   --no-audio          video only   --no-warp   lay the song under straight (no low-pass, no slowing)   --letterbox   2.39:1 bars (landscape)
//   --bio               the portrait end card says "link in bio"   --keep-frames   do not delete the PNGs   --gpu   use the machine's GPU (needs one)
//   --frames jpg        write quality-95 JPEG frames instead of PNG (about a quarter of the disk; use it for the full-resolution presets)
//   --shutter N         motion blur: N exposures per frame over a thirtieth of a second, averaged under the overlays (default: each shot's own
//                       count, so the portrait cut smears its whip pans, flinches and the fall; --shutter 1 turns it off)
//   --cta web           the portrait end card says "play it free in your browser" instead of the Steam line
//   --headed            a visible browser window (needs a display; with --gpu this is the fast path on a real machine)
//   --serve [--port N]  only serve the repo for the live preview (index.html?trailer=1) and keep running
'use strict';
const http = require('http'), fs = require('fs'), path = require('path'), os = require('os'), { execFileSync, spawnSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const args = process.argv.slice(2);
const has = (k) => args.includes(k), opt = (k, d) => { const i = args.indexOf(k); return i >= 0 && i + 1 < args.length ? args[i + 1] : d; };
// frame files: PNG by default; --frames jpg writes quality-95 JPEGs (the film grain keeps full-size PNGs from compressing)
const FX = opt('--frames', 'png') === 'jpg' ? 'jpg' : 'png';
const PRESETS = {
  preview: { w: 640, h: 360, fps: 12, aspect: 'landscape', quality: 'medium', name: 'topbunk-trailer-preview-360p12' },
  steam: { w: 1920, h: 1080, fps: 30, aspect: 'landscape', quality: 'high', name: 'topbunk-trailer-1080p30' },
  'social-preview': { w: 360, h: 640, fps: 12, aspect: 'portrait', quality: 'medium', name: 'topbunk-social-preview-360x640-12' },
  social: { w: 1080, h: 1920, fps: 30, aspect: 'portrait', quality: 'high', name: 'topbunk-social-1080x1920-30' },
};
const MIME = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript', '.mjs': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.png': 'image/png', '.jpg': 'image/jpeg', '.webp': 'image/webp', '.glb': 'model/gltf-binary', '.hdr': 'application/octet-stream', '.woff2': 'font/woff2', '.mp3': 'audio/mpeg', '.wav': 'audio/wav', '.wasm': 'application/wasm', '.svg': 'image/svg+xml', '.ico': 'image/x-icon' };
const log = (...a) => console.log(new Date().toISOString().slice(11, 19), ...a);

// ---------- the static server (index.html gets the live-preview boot script; nothing else changes) ----------
function serve(port) {
  const srv = http.createServer((req, res) => {
    let p = decodeURIComponent(req.url.split('?')[0].split('#')[0]); if (p === '/') p = '/index.html';
    const f = path.join(ROOT, p);
    if (!f.startsWith(ROOT) || !fs.existsSync(f) || fs.statSync(f).isDirectory()) { res.writeHead(404); return res.end('not found'); }
    const type = MIME[path.extname(f).toLowerCase()] || 'application/octet-stream';
    res.writeHead(200, { 'Content-Type': type, 'Cache-Control': 'no-store', 'Access-Control-Allow-Origin': '*' });
    if (p === '/index.html') return res.end(fs.readFileSync(f, 'utf8').replace('</body>', '  <script type="module" src="trailer/boot.js"></script>\n</body>'));
    fs.createReadStream(f).pipe(res);
  });
  return new Promise((resolve, reject) => { srv.on('error', reject); srv.listen(port, '127.0.0.1', () => resolve(srv)); });
}

// the frozen clock: the game's requestAnimationFrame loop only runs when __pump(ms) is called, and every clock agrees with it
const INIT = `(() => {
  let now = 0, queue = [], id = 0; const epoch = 1700000000000;
  window.requestAnimationFrame = (cb) => { queue.push(cb); return ++id; };
  window.cancelAnimationFrame = () => {};
  performance.now = () => now; Date.now = () => epoch + now;
  window.__pump = (ms) => { now += ms; const q = queue; queue = []; for (const cb of q) { try { cb(now); } catch (e) { console.error('rAF callback failed: ' + (e && e.stack || e)); } } return now; };
  // a seeded Math.random, so the grain and the flicker come out the same every run
  let s = 20021031 >>> 0; Math.random = () => { s = (s + 0x6D2B79F5) >>> 0; let t = s; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
})();`;

function ensureMusic(file) {
  if (fs.existsSync(file) && fs.existsSync(path.join(__dirname, 'music', 'box_note.wav'))) return file;   // (the last file gen_music.js writes)
  log('no placeholder music yet: generating it (trailer/gen_music.js)');
  execFileSync(process.execPath, [path.join(__dirname, 'gen_music.js')], { stdio: 'inherit' });
  return file;
}
const probeDuration = (f) => parseFloat(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f]).toString()) || 0;
const fmt = (s) => { s = Math.max(0, Math.round(s)); return `${String(Math.floor(s / 3600)).padStart(2, '0')}:${String(Math.floor(s / 60) % 60).padStart(2, '0')}:${String(s % 60).padStart(2, '0')}`; };

// ---------- the soundtrack: one ffmpeg filter graph ----------
// a small room: a few early reflections of a bedroom's walls (wet: 0..1). It puts a voice behind a wall, or a record in the house
const ROOM = (wet) => `aecho=1:${(1 - wet * 0.35).toFixed(2)}:13|23|31|43|59:${[0.5, 0.42, 0.35, 0.27, 0.2].map((d) => (d * wet).toFixed(3)).join('|')}`;
// plan.duck { gain, ramp }: the song steps down to gain under every voice line (the cues from assets/audio/vo, unless a cue says duck: false),
// ramping over ramp seconds either side, so the lines read over the bed. boot.js does the same with the same windows.
function duckExpr(windows, { gain = 0.4, ramp = 0.3 } = {}) {
  const r = ramp.toFixed(3), tri = windows.map(([a, b]) => `clip(min((t-${(a - ramp).toFixed(3)})/${r},(${(b + ramp).toFixed(3)}-t)/${r}),0,1)`);
  return `1-${(1 - gain).toFixed(3)}*clip(${tri.join('+')},0,1)`;
}
const isVoice = (c) => c.duck !== false && /(^|\/)assets\/audio\/vo\//.test(c.file);
function buildMix({ music, cues, plan, duration, warp, outWav, scratch }) {
  const SR = 44100, inputs = [music], parts = [], labels = [], bed = [];
  const idx = (f) => { let i = inputs.indexOf(f); if (i < 0) { inputs.push(f); i = inputs.length - 1; } return i; };
  const durs = {}, dur = (f) => (durs[f] ??= probeDuration(f));
  const ducks = plan.duck ? cues.filter((c) => isVoice(c) && fs.existsSync(path.resolve(ROOT, c.file))).map((c) => [c.t, c.t + (c.dur || dur(path.resolve(ROOT, c.file)) - (c.src || 0))]) : [];
  plan.segments.forEach((s, i) => {
    const [a, b] = s.out, len = b - a, rate = warp ? (s.rate || 1) : 1, srcLen = len * rate;
    let f = `[0:a]atrim=start=${s.src}:end=${(s.src + srcLen).toFixed(4)},asetpts=PTS-STARTPTS,aformat=sample_fmts=fltp:sample_rates=${SR}:channel_layouts=stereo`;
    if (rate !== 1) f += `,asetrate=${Math.round(SR * rate)},aresample=${SR}`;
    if (warp && s.lp) f += `,lowpass=f=${s.lp}`;
    if (s.hp) f += `,highpass=f=${s.hp}`;
    if (warp && s.vib) f += `,vibrato=f=0.45:d=${s.vib}`;
    if (s.mono) f += ',pan=stereo|c0=0.5*c0+0.5*c1|c1=0.5*c0+0.5*c1';   // (a camcorder's mic: one channel)
    if (s.room) f += `,${ROOM(s.room)}`;
    f += `,volume=${s.gain ?? 1}`;
    if (s.fadeIn) f += `,afade=t=in:st=0:d=${s.fadeIn}`;
    if (s.fadeOut) f += `,afade=t=out:st=${(len - s.fadeOut).toFixed(3)}:d=${s.fadeOut}`;
    // (asetpts after adelay: the delay's leading silence comes out with no timestamps after an atrim, amix then starts late and the final atrim cuts the end)
    f += `,atrim=end=${len.toFixed(4)},adelay=${Math.round(a * 1000)}|${Math.round(a * 1000)},asetpts=N/SR/TB,apad=whole_dur=${duration}[m${i}]`;
    parts.push(f); bed.push(`[m${i}]`);
  });
  if (ducks.length && bed.length) {   // (small frames, so the gain moves in 6 ms steps rather than whole frames)
    parts.push(`${bed.join('')}amix=inputs=${bed.length}:normalize=0:dropout_transition=0,asetnsamples=n=256:p=0,volume='${duckExpr(ducks, plan.duck)}':eval=frame[bed]`);
    labels.push('[bed]');
  } else labels.push(...bed);
  cues.forEach((c, i) => {
    const file = path.resolve(ROOT, c.file);
    if (!fs.existsSync(file)) { log('cue file missing, skipped:', c.file); return; }
    const len = c.dur || dur(file) - (c.src || 0);
    let f = `[${idx(file)}:a]aformat=sample_fmts=fltp:sample_rates=${SR}:channel_layouts=stereo`;
    if (c.src || c.dur) f += `,atrim=start=${c.src || 0}${c.dur ? `:end=${(c.src || 0) + c.dur}` : ''},asetpts=PTS-STARTPTS`;   // src: where in the file the cue starts
    if (c.lp) f += `,lowpass=f=${c.lp}`;
    if (c.hp) f += `,highpass=f=${c.hp}`;
    if (c.drive) f += `,volume=${c.drive},asoftclip=type=tanh,volume=${(1 / Math.sqrt(c.drive)).toFixed(3)}`;   // drive: saturate it, so a low hit grows harmonics a phone can play
    if (c.room) f += `,${ROOM(c.room)}`;
    f += `,volume=${c.gain ?? 1}`;
    if (c.fadeIn) f += `,afade=t=in:st=0:d=${c.fadeIn}`;
    if (c.fadeOut) f += `,afade=t=out:st=${Math.max(0, len - c.fadeOut).toFixed(3)}:d=${c.fadeOut}`;
    if (c.pan) { const p = Math.max(-1, Math.min(1, c.pan)), gl = (Math.cos((p + 1) * Math.PI / 4) * Math.SQRT2).toFixed(4), gr = (Math.sin((p + 1) * Math.PI / 4) * Math.SQRT2).toFixed(4); f += `,pan=stereo|c0=${gl}*c0|c1=${gr}*c1`; }
    f += `,adelay=${Math.round(c.t * 1000)}|${Math.round(c.t * 1000)},asetpts=N/SR/TB,apad=whole_dur=${duration}[c${i}]`;   // (every track runs the full length: amix then never ends early)
    parts.push(f); labels.push(`[c${i}]`);
  });
  let tail = `${labels.join('')}amix=inputs=${labels.length}:normalize=0:dropout_transition=0`;
  for (const [a, b] of plan.mute || []) tail += `,volume=enable='between(t,${a},${b})':volume=0`;
  tail += `,atrim=end=${duration},alimiter=limit=0.95:level=false[out]`;
  parts.push(tail);
  const script = path.join(scratch, 'mix.filter'); fs.writeFileSync(script, parts.join(';\n'));
  const cmd = ['-y', '-hide_banner', '-loglevel', 'error', ...inputs.flatMap((f) => ['-i', f]), '-filter_complex_script', script, '-map', '[out]', '-ar', String(SR), '-ac', '2', '-c:a', 'pcm_s16le', outWav];
  log('mixing audio:', labels.length, 'tracks ->', path.relative(ROOT, outWav));
  const r = spawnSync('ffmpeg', cmd, { stdio: 'inherit' }); if (r.status !== 0) throw new Error('ffmpeg audio mix failed');
  if (plan.loudness !== undefined) master(outWav, plan.loudness, plan.truePeak ?? -1, scratch);
  if (plan.muteFloor !== undefined && (plan.mute || []).length) tapeHiss(outWav, plan.mute, plan.muteFloor, scratch);
  return outWav;
}
// a tape never goes digitally silent: under each mute window the tape's own hiss carries on at `level` dBFS (rms). It goes in after the
// mastering so it lands at exactly that level; at -50 dBFS it moves neither the loudness nor the peak
const HISS_RMS = -19.4;   // band-limited pink noise at full amplitude, measured with astats
function tapeHiss(wav, windows, level, scratch) {
  const tmp = path.join(scratch, 'mix-hiss.wav'), on = windows.map(([a, b]) => `between(t,${a},${b})`).join('+');
  const graph = `anoisesrc=d=${probeDuration(wav).toFixed(3)}:c=pink:r=44100:a=1:s=7,highpass=f=500,lowpass=f=9000,volume=${(level - HISS_RMS).toFixed(2)}dB,`
    + `asetnsamples=n=256:p=0,volume='${on}':eval=frame,aformat=channel_layouts=stereo[h];[0:a][h]amix=inputs=2:normalize=0:duration=first[out]`;
  const r = spawnSync('ffmpeg', ['-y', '-hide_banner', '-loglevel', 'error', '-i', wav, '-filter_complex', graph, '-map', '[out]', '-c:a', 'pcm_s16le', tmp], { stdio: 'inherit' });
  if (r.status !== 0) throw new Error('ffmpeg tape hiss failed');
  fs.renameSync(tmp, wav);
  log(`tape hiss at ${level} dBFS under ${windows.length} mute window(s)`);
}
// integrated loudness (LUFS) and true peak (dBTP) of a file, from ffmpeg's EBU R128 meter
function loudness(file) {
  const r = spawnSync('ffmpeg', ['-hide_banner', '-nostats', '-i', file, '-af', 'ebur128=peak=true', '-f', 'null', '-'], { encoding: 'utf8' });
  const s = r.stderr.slice(r.stderr.lastIndexOf('Summary:')), num = (re) => { const m = re.exec(s); return m ? parseFloat(m[1]) : NaN; };
  return { I: num(/I:\s+(-?[\d.]+) LUFS/), LRA: num(/LRA:\s+(-?[\d.]+) LU/), TP: num(/Peak:\s+(-?[\d.]+) dBFS/) };
}
// one gain to the target loudness, then a limiter for the peaks: the mix keeps its dynamics (the quiet bed stays quiet, the scare still jumps),
// and the platforms' own normalisation has nothing left to turn down or clip. The limiter takes some loudness off the scare, so one more
// small push follows, capped at 1.5 dB: past that the limiter flattens the scare into the run and the hook
function master(wav, target, ceiling, scratch) {
  const before = loudness(wav), tmp = path.join(scratch, 'mix-master.wav');
  const pass = (gain) => {
    const r = spawnSync('ffmpeg', ['-y', '-hide_banner', '-loglevel', 'error', '-i', wav, '-af', `volume=${gain.toFixed(2)}dB,alimiter=limit=${Math.pow(10, (ceiling - 0.6) / 20).toFixed(4)}:attack=2:release=60:level=false`, '-c:a', 'pcm_s16le', tmp], { stdio: 'inherit' });
    if (r.status !== 0) throw new Error('ffmpeg mastering failed');
    fs.renameSync(tmp, wav); return loudness(wav);
  };
  let after = pass(target - before.I);
  if (after.I < target - 0.3) after = pass(Math.min(1.5, target - after.I));
  log(`loudness ${before.I} LUFS -> ${after.I} LUFS (target ${target}), range ${after.LRA} LU, true peak ${after.TP} dBTP (ceiling ${ceiling})`);
}

// ---------- main ----------
async function main() {
  const port = +opt('--port', 8700);
  if (has('--serve')) {
    ensureMusic(path.join(__dirname, 'music', 'placeholder.wav'));   // (boot.js plays the generated files: a fresh clone has none)
    const srv = await serve(port);
    log(`serving ${ROOT} at http://127.0.0.1:${port}/  (open /index.html?trailer=1 or /index.html?trailer=1&aspect=portrait)`);
    return new Promise(() => { process.on('SIGINT', () => { srv.close(); process.exit(0); }); });
  }
  const presetName = opt('--preset', 'preview'), preset = PRESETS[presetName];
  if (!preset) throw new Error(`unknown preset ${presetName} (${Object.keys(PRESETS).join(', ')})`);
  const aspect = opt('--aspect', preset.aspect), portrait = aspect === 'portrait';
  const fps = +opt('--fps', preset.fps), W = preset.w, H = preset.h, quality = opt('--quality', preset.quality), shadow = +opt('--shadow', 0) || 0, res = +opt('--res', 1) || 1;
  const outDir = path.resolve(ROOT, opt('--out', path.join(__dirname, 'out'))), scratch = path.resolve(opt('--scratch', path.join(os.tmpdir(), 'topbunk-trailer')), preset.name);
  const framesDir = path.join(scratch, 'frames'); fs.mkdirSync(framesDir, { recursive: true }); fs.mkdirSync(outDir, { recursive: true });
  const music = path.resolve(ROOT, opt('--music', ensureMusic(path.join(__dirname, 'music', 'placeholder.wav'))));
  if (!fs.existsSync(music)) throw new Error('music file not found: ' + music);
  const cues = JSON.parse(fs.readFileSync(path.join(__dirname, portrait ? 'cues_portrait.json' : 'cues.json'), 'utf8'));
  const plan = JSON.parse(fs.readFileSync(path.join(__dirname, 'music_plan.json'), 'utf8'))[aspect];
  const contact = has('--contact'), every = +opt('--every', 1) || 1, range = (opt('--range', '') || '').split('-').map(Number), resume = has('--resume');
  const { chromium } = require('playwright');
  const srv = await serve(port);
  const gpu = has('--gpu');
  const browser = await chromium.launch({ headless: !has('--headed'), args: gpu ? ['--ignore-gpu-blocklist', '--enable-gpu-rasterization', '--autoplay-policy=no-user-gesture-required'] : ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--autoplay-policy=no-user-gesture-required'] });
  const page = await browser.newPage({ viewport: { width: W, height: H }, deviceScaleFactor: 1 });
  const pageLog = fs.createWriteStream(path.join(scratch, 'page.log'));
  page.on('console', (m) => { const line = `[${m.type()}] ${m.text()}`; pageLog.write(line + '\n'); if (m.type() === 'error') log('page:', line.slice(0, 300)); });
  page.on('pageerror', (e) => { pageLog.write('[pageerror] ' + e.stack + '\n'); log('page error:', e.message); });
  await page.addInitScript(INIT);
  const t0 = Date.now();
  await page.goto(`http://127.0.0.1:${port}/index.html#shot`, { waitUntil: 'load', timeout: 180000 });   // #shot: the game keeps its drawing buffer, so a screenshot never catches a cleared canvas
  await page.waitForFunction(() => window.__game && window.__game.E, null, { polling: 200, timeout: 180000 });
  await page.waitForLoadState('networkidle', { timeout: 180000 });
  await page.waitForFunction(() => window.__game.E.rig && window.__game.mom.rig && window.__game.dad.rig, null, { polling: 200, timeout: 180000 });
  await page.waitForTimeout(1500);
  log(`game loaded in ${((Date.now() - t0) / 1000).toFixed(1)} s; ${W}x${H} @ ${fps} fps, ${aspect}, quality ${quality}${shadow ? `, shadows ${shadow}` : ''}${res !== 1 ? `, res ${res}` : ''}`);
  const info = await page.evaluate(async ([o, b]) => {
    const m = await import('/trailer/trailer.js');
    window.__trailer = m.attach(window.__game, o);
    await window.__trailer.begin(b);
    return { duration: window.__trailer.duration, shots: window.__trailer.SHOTS.map((s) => ({ id: s.id, t: s.t, dur: s.dur, teaser: s.teaser })) };
  }, [{ aspect, fps, linkInBio: has('--bio'), cta: opt('--cta', ''), shutter: has('--shutter') ? Math.max(1, Math.min(8, Math.round(+opt('--shutter', 1) || 1))) : undefined }, { quality, shadow, res, letterbox: has('--letterbox') }]);
  const duration = info.duration, total = Math.ceil(duration * fps);
  log(`${info.shots.length} shots, ${duration} s, ${total} frames`);
  // which frames to capture
  const wanted = new Set();
  if (contact) for (const s of info.shots) wanted.add(Math.min(total - 1, Math.floor((s.t + s.dur / 2) * fps)));
  else for (let i = 0; i < total; i++) if (i % every === 0 && (!range[0] && range[0] !== 0 || (i >= (range[0] || 0) && i <= (range[1] ?? total)))) wanted.add(i);
  let lastShot = '', captured = 0, tStart = Date.now(), times = [];
  for (let i = 0; i < total; i++) {
    const file = path.join(framesDir, String(i).padStart(6, '0') + '.' + FX), take = wanted.has(i) && !(resume && fs.existsSync(file));
    const fa = Date.now();
    const r = await page.evaluate(([n, cap]) => window.__trailer.frame(n, cap), [i, take]);
    if (take) await page.screenshot({ path: file, ...(FX === 'jpg' ? { type: 'jpeg', quality: 95 } : { type: 'png' }), animations: 'disabled', caret: 'hide', timeout: 900000 });
    if (r.shot !== lastShot) { lastShot = r.shot; log(`shot ${r.shot} at ${r.t.toFixed(2)} s (frame ${i})${r.exposures > 1 ? `, ${r.exposures} exposures per frame` : ''}`); }
    if (take) captured++;
    const dt = (Date.now() - fa) / 1000; if (take) times.push(dt); if (times.length > 30) times.shift();
    if (take && (captured % 10 === 0 || captured === 1)) {
      const avg = times.reduce((a, b) => a + b, 0) / times.length, left = [...wanted].filter((n) => n > i).length;
      log(`frame ${i}/${total} ${r.shot}  ${dt.toFixed(2)} s (avg ${avg.toFixed(2)} s/frame)  ETA ${fmt(left * avg)}  elapsed ${fmt((Date.now() - tStart) / 1000)}`);
    }
  }
  const elapsed = (Date.now() - tStart) / 1000;
  log(`captured ${captured} frames in ${fmt(elapsed)} (${(elapsed / Math.max(1, captured)).toFixed(2)} s per frame)`);
  await browser.close(); srv.close(); pageLog.end();
  if (contact) {
    // the contact sheet: every shot's middle frame, named by shot
    const dir = path.join(outDir, preset.name + '-contact'); fs.mkdirSync(dir, { recursive: true });
    for (const s of info.shots) { const n = Math.min(total - 1, Math.floor((s.t + s.dur / 2) * fps)), src = path.join(framesDir, String(n).padStart(6, '0') + '.' + FX); if (fs.existsSync(src)) fs.copyFileSync(src, path.join(dir, `${String(s.t).padStart(6, '0')}-${s.id}.${FX}`)); }
    log('contact frames in', path.relative(ROOT, dir)); return;
  }
  if (wanted.size !== total) { log('partial render (frames kept in ' + framesDir + '); no video encoded'); return; }
  // sound, then picture + sound
  const outFile = path.join(outDir, preset.name + '.mp4');
  let mix = null;
  if (!has('--no-audio')) mix = buildMix({ music, cues, plan, duration, warp: !has('--no-warp'), outWav: path.join(scratch, 'mix.wav'), scratch });
  log('encoding', path.relative(ROOT, outFile));
  const enc = ['-y', '-hide_banner', '-loglevel', 'error', '-framerate', String(fps), '-pattern_type', 'glob', '-i', path.join(framesDir, '*.' + FX), ...(mix ? ['-i', mix] : []),
    '-frames:v', String(total), '-c:v', 'libx264', '-preset', 'slow', '-crf', '18', '-pix_fmt', 'yuv420p', '-r', String(fps), ...(mix ? ['-c:a', 'aac', '-b:a', '256k', '-ar', '44100', '-shortest'] : ['-an']), '-movflags', '+faststart', outFile];
  const r = spawnSync('ffmpeg', enc, { stdio: 'inherit' }); if (r.status !== 0) throw new Error('ffmpeg encode failed');
  // a ten-second teaser (the run, the cut, the scare) at gif size; a shot with `teaser: s` starts it s seconds into that shot
  const tShot = info.shots.find((s) => s.teaser !== undefined && s.teaser !== null);
  const teaser = path.join(outDir, preset.name + '-teaser10s.mp4'), ts = tShot ? tShot.t + tShot.teaser : portrait ? Math.max(0, duration - 11.5) : 100;
  spawnSync('ffmpeg', ['-y', '-hide_banner', '-loglevel', 'error', '-ss', String(ts), '-t', '10', '-i', outFile, '-vf', portrait ? 'scale=270:-2' : 'scale=480:-2', '-c:v', 'libx264', '-crf', '24', '-pix_fmt', 'yuv420p', '-c:a', 'aac', '-b:a', '96k', '-movflags', '+faststart', teaser], { stdio: 'inherit' });
  if (!has('--keep-frames')) fs.rmSync(framesDir, { recursive: true, force: true });
  log('done:', path.relative(ROOT, outFile), fs.existsSync(teaser) ? 'and ' + path.relative(ROOT, teaser) : '');
}
